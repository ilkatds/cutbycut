// Dev tool: translate the interface (tools/i18n_source.json) and the guide into other languages
// with Claude Code CLI. Output: renderer/lang/<code>.js and renderer/lang/guide_<code>.js
// Usage: node tools/translate.mjs ui uk,en,pl,...   |   node tools/translate.mjs guide uk,en
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const LANG_DIR = path.join(ROOT, 'renderer', 'lang');
fs.mkdirSync(LANG_DIR, { recursive: true });
const NAMES = { uk: 'Ukrainian', en: 'English', pl: 'Polish', de: 'German', es: 'Spanish', fr: 'French', it: 'Italian', pt: 'Portuguese (Brazil)', tr: 'Turkish' };

function findClaude() {
  const root = path.join(process.env.LOCALAPPDATA || '', 'Claude-Data');
  let best = null, bestT = 0;
  for (const a of fs.readdirSync(root)) {
    const cc = path.join(root, a, 'claude-code');
    if (!fs.existsSync(cc)) continue;
    for (const v of fs.readdirSync(cc)) for (const h of fs.readdirSync(path.join(cc, v))) {
      const p = path.join(cc, v, h, 'claude.exe');
      if (fs.existsSync(p)) { const t = fs.statSync(p).mtimeMs; if (t > bestT) { bestT = t; best = p; } }
    }
  }
  return best;
}
const CLAUDE = findClaude();
const CWD = path.join(os.tmpdir(), 'sklejka_translate');
fs.mkdirSync(CWD, { recursive: true });

function ask(prompt) {
  return new Promise((resolve, reject) => {
    const p = spawn(CLAUDE, ['-p', '--output-format', 'json', '--model', 'claude-sonnet-5-5', '--max-turns', '1', '--disallowedTools', 'Bash,Edit,Write,Read,Glob,Grep,WebFetch,WebSearch,Agent,NotebookEdit'], { cwd: CWD, windowsHide: true });
    let out = '', err = '';
    p.stdout.on('data', (d) => { out += d.toString('utf8'); });
    p.stderr.on('data', (d) => { err += d.toString('utf8'); });
    p.on('close', () => {
      try { const j = JSON.parse(out.trim().split(/\r?\n/).filter(Boolean).pop()); if (j.is_error) return reject(new Error(j.result)); resolve(j.result); }
      catch (e) { reject(new Error((err || out).slice(-500))); }
    });
    p.stdin.end(prompt, 'utf8');
  });
}
function parseJson(t) {
  let s = t.trim().replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '');
  const a = Math.min(...['{', '['].map((c) => { const i = s.indexOf(c); return i < 0 ? Infinity : i; }));
  const b = Math.max(s.lastIndexOf('}'), s.lastIndexOf(']'));
  return JSON.parse(s.slice(a, b + 1));
}
async function pool(tasks, n) {
  let i = 0;
  const results = [];
  await Promise.all(Array.from({ length: n }, async () => { while (i < tasks.length) { const k = i++; results[k] = await tasks[k](); } }));
  return results;
}

async function translateUI(code, deltaOnly) {
  let src = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'i18n_source.json'), 'utf8'));
  let prev = {};
  const prevFile = path.join(LANG_DIR, `${code}.js`);
  if (deltaOnly && fs.existsSync(prevFile)) {
    const t = fs.readFileSync(prevFile, 'utf8');
    prev = JSON.parse(t.slice(t.indexOf('= {') + 2, t.lastIndexOf('}') + 1));
    src = src.filter((k) => !(k in prev));
    console.log(code, 'missing', src.length);
    if (!src.length) return;
  }
  const chunks = [];
  for (let i = 0; i < src.length; i += 160) chunks.push(src.slice(i, i + 160));
  const dict = { ...prev };
  await pool(chunks.map((chunk, ci) => async () => {
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        const res = await ask(`You translate the user interface of a desktop video editor ("Склейка") from Russian into ${NAMES[code]}.
Rules: keep placeholders like {0} {1} exactly; keep emoji, symbols (⇪ ✂ ▶ ◇ …), keyboard keys (Ctrl+B, Del, Space…), numbers, file extensions, brand names (FFmpeg, Whisper, Claude, Openverse, Pixabay, Pexels, remove.bg, YouTube, TikTok, CapCut); keep it as short as the original (these are buttons and labels); use the usual video-editing terms of that language; keep leading/trailing punctuation.
Return ONLY a JSON object mapping every Russian string (exactly as given) to its translation, no comments.
Strings:
${JSON.stringify(chunk, null, 0)}`);
        Object.assign(dict, parseJson(res));
        console.log(code, 'chunk', ci + 1, '/', chunks.length);
        return;
      } catch (e) { console.log(code, 'chunk', ci + 1, 'retry', e.message.slice(0, 120)); }
    }
  }), 3);
  const file = path.join(LANG_DIR, `${code}.js`);
  fs.writeFileSync(file, `// ${NAMES[code]} interface (generated by tools/translate.mjs)\nwindow.LANG_DICTS = window.LANG_DICTS || {};\nwindow.LANG_DICTS[${JSON.stringify(code)}] = ${JSON.stringify(dict, null, 1)};\n`, 'utf8');
  console.log(code, 'done', Object.keys(dict).length, 'of', src.length);
}

async function translateGuide(code) {
  const src = fs.readFileSync(path.join(ROOT, 'renderer', 'js', 'guide.js'), 'utf8');
  const block = src.slice(src.indexOf('const GUIDE_RU = ['), src.indexOf('function guideFor'));
  // evaluate the GUIDE_RU literal
  const GUIDE_RU = new Function(block.replace('const GUIDE_RU =', 'return').replace(/;\s*$/, ''))();
  const out = [];
  const parts = [GUIDE_RU.slice(0, 9), GUIDE_RU.slice(9)];
  const res = await pool(parts.map((part) => async () => {
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        return parseJson(await ask(`Translate this help guide of a video editor from Russian into ${NAMES[code]}. It is a JSON array of sections {id, icon, title, html}. Translate "title" and the text inside "html"; keep all HTML tags, <kbd> key names, ids and icons unchanged. Return ONLY the JSON array.
${JSON.stringify(part)}`));
      } catch (e) { console.log('guide', code, 'retry', e.message.slice(0, 120)); }
    }
    return part;
  }), 2);
  for (const r of res) out.push(...r);
  fs.writeFileSync(path.join(LANG_DIR, `guide_${code}.js`), `// ${NAMES[code]} guide (generated)\nwindow.GUIDE_${code.toUpperCase()} = ${JSON.stringify(out, null, 1)};\n`, 'utf8');
  console.log('guide', code, 'done', out.length);
}

const [mode, langs] = process.argv.slice(2);
const list = (langs || '').split(',').filter(Boolean);
for (const code of list) {
  if (mode === 'guide') await translateGuide(code);
  else await translateUI(code, mode === 'delta');
}
