function guideFor(lang) {
  const g = window['GUIDE_' + lang.toUpperCase()];
  if (lang === 'ru' || (!g && lang === 'ru')) return GUIDE_RU;
  return g || window.GUIDE_EN || GUIDE_RU;
}
function loadGuideScript(lang) {
  return new Promise((res) => {
    if (lang === 'ru' || window['GUIDE_' + lang.toUpperCase()]) return res();
    const s = document.createElement('script');
    s.src = `lang/guide_${lang}.js`;
    s.onload = res;
    s.onerror = () => { if (lang !== 'en') loadGuideScript('en').then(res); else res(); };
    document.head.append(s);
  });
}
async function openGuide(sectionId) {
  const lang = I18N.lang;
  await loadGuideScript(lang);
  const G = guideFor(lang);
  openModal((box) => {
    box.style.width = '980px'; box.style.maxWidth = '95vw'; box.style.padding = '0';
    box.setAttribute('data-no-i18n', '');
    const nav = h('div', { style: { width: '250px', borderRight: '1px solid var(--line)', padding: '14px 10px', overflowY: 'auto', maxHeight: '70vh', flex: 'none' } });
    const content = h('div', { class: 'guide', style: { flex: 1, padding: '20px 26px', overflowY: 'auto', maxHeight: '70vh', lineHeight: 1.65, userSelect: 'text' } });
    const search = h('input', { type: 'text', placeholder: '🔎', style: { width: '100%', marginBottom: '10px' } });
    nav.append(search);
    const list = h('div');
    nav.append(list);
    const show = (sec) => {
      content.innerHTML = `<h2 style="margin-top:0">${sec.icon} ${sec.title}</h2>${sec.html}`;
      $$('button', list).forEach((b) => b.classList.toggle('on', b.dataset.id === sec.id));
      content.scrollTop = 0;
    };
    const draw = (q) => {
      list.innerHTML = '';
      const ql = q.trim().toLowerCase();
      for (const sec of G) {
        if (ql && !(sec.title + sec.html.replace(/<[^>]+>/g, ' ')).toLowerCase().includes(ql)) continue;
        list.append(h('button', { class: 'ghost', 'data-id': sec.id, style: { display: 'block', width: '100%', textAlign: 'left', padding: '7px 9px' }, onclick: () => show(sec) }, `${sec.icon}  ${sec.title}`));
      }
    };
    search.addEventListener('input', () => { draw(search.value); const first = $('button', list); if (first) first.click(); });
    draw('');
    box.append(h('div', { style: { display: 'flex', minHeight: '560px' } }, nav, content));
    box.append(h('div', { style: { borderTop: '1px solid var(--line)', padding: '10px 16px', display: 'flex', justifyContent: 'space-between' } },
      h('button', { onclick: () => { closeModal(); startTour(); } }, '🧭 ' + (lang === 'ru' ? 'Экскурсия' : lang === 'uk' ? 'Екскурсія' : 'Tour')),
      h('button', { class: 'primary', onclick: closeModal }, 'OK')));
    show(G.find((s) => s.id === sectionId) || G[0]);
  });
}

