function startTour(i = 0) {
  $$('.tourTip, .tourHole').forEach((e) => e.remove());
  if (i >= TOUR.length) { saveSetting({ tourDone: true }); return; }
  const [sel, text] = TOUR[i];
  const target = $(sel);
  if (!target) return startTour(i + 1);
  const r = target.getBoundingClientRect();
  const hole = h('div', { class: 'tourHole', style: { position: 'fixed', left: r.left - 4 + 'px', top: r.top - 4 + 'px', width: r.width + 8 + 'px', height: r.height + 8 + 'px', borderRadius: '10px', boxShadow: '0 0 0 9999px rgba(0,0,0,.6)', border: '2px solid var(--accent)', zIndex: 300, pointerEvents: 'none' } });
  const tip = h('div', { class: 'tourTip', style: { position: 'fixed', zIndex: 301, width: '320px', background: 'var(--bg2)', border: '1px solid var(--accent)', borderRadius: '10px', padding: '14px 16px', boxShadow: '0 10px 30px rgba(0,0,0,.5)', lineHeight: 1.5 } },
    h('div', { style: { color: 'var(--dim)', fontSize: '11px', marginBottom: '6px' } }, `${i + 1} / ${TOUR.length}`),
    h('div', {}, text),
    h('div', { class: 'btnRow', style: { marginTop: '12px', justifyContent: 'flex-end' } },
      h('button', { onclick: () => { $$('.tourTip, .tourHole').forEach((e) => e.remove()); saveSetting({ tourDone: true }); } }, 'Пропустить'),
      h('button', { class: 'primary', onclick: () => startTour(i + 1) }, i === TOUR.length - 1 ? 'Готово' : 'Далее')));
  document.body.append(hole, tip);
  const tw = 320, th = tip.offsetHeight || 140;
  let x = r.right + 14, y = r.top;
  if (x + tw > innerWidth - 10) x = r.left - tw - 14;
  if (x < 10) { x = Math.min(innerWidth - tw - 10, Math.max(10, r.left)); y = r.bottom + 14; }
  if (y + th > innerHeight - 10) y = Math.max(10, r.top - th - 14);
  Object.assign(tip.style, { left: x + 'px', top: y + 'px' });
}
